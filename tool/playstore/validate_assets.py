"""Validates every Play Store asset against Google's published rules.

Run from the repository root:

    python3 tool/playstore/validate_assets.py

Writes deploy/playstore/ASSET_CHECK.md and exits non zero when something would
be rejected by the Play Console.
"""

from __future__ import annotations

import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
GRAPHICS = ROOT / "deploy/playstore/graphics"
REPORT = ROOT / "deploy/playstore/ASSET_CHECK.md"

MAX_BYTES = 8 * 1024 * 1024
SCREENSHOT_MIN = 320
SCREENSHOT_MAX = 3840
MIN_SCREENSHOTS = 2
MAX_SCREENSHOTS = 8

results: list[tuple[str, str, str, bool]] = []


def record(group: str, name: str, detail: str, ok: bool) -> None:
    results.append((group, name, detail, ok))


def check_exact(path: pathlib.Path, width: int, height: int, label: str) -> None:
    if not path.exists():
        record(label, path.name, "missing", False)
        return
    with Image.open(path) as image:
        size_ok = image.size == (width, height)
        mode_ok = image.mode in {"RGB", "RGBA"}
        bytes_ok = path.stat().st_size <= MAX_BYTES
        detail = (
            f"{image.size[0]}x{image.size[1]}, {image.mode}, "
            f"{path.stat().st_size / 1024:.0f} KB"
        )
        record(label, path.name, detail, size_ok and mode_ok and bytes_ok)


def check_screenshots(folder: str, label: str) -> None:
    directory = GRAPHICS / "screenshots" / folder
    files = sorted(directory.glob("*.png"))
    if not (MIN_SCREENSHOTS <= len(files) <= MAX_SCREENSHOTS):
        record(label, folder, f"{len(files)} images (needs 2-8)", False)
        return
    all_ok = True
    for path in files:
        with Image.open(path) as image:
            width, height = image.size
            ratio = height / width
            size_ok = (
                SCREENSHOT_MIN <= width <= SCREENSHOT_MAX
                and SCREENSHOT_MIN <= height <= SCREENSHOT_MAX
            )
            ratio_ok = 0.5 <= ratio <= 2.0
            bytes_ok = path.stat().st_size <= MAX_BYTES
            ok = size_ok and ratio_ok and bytes_ok
            all_ok = all_ok and ok
            record(
                label,
                path.name,
                f"{width}x{height}, {path.stat().st_size / 1024:.0f} KB"
                + ("" if ok else "  <-- FAIL"),
                ok,
            )
    record(
        label,
        folder,
        f"{len(files)} images, all valid" if all_ok else "errors",
        all_ok,
    )


def main() -> int:
    check_exact(GRAPHICS / "app-icon-512.png", 512, 512, "Store icon")
    check_exact(GRAPHICS / "feature-graphic-1024x500.png", 1024, 500, "Feature graphic")
    check_exact(GRAPHICS / "app-icon-round-512.png", 512, 512, "Round icon")
    check_exact(GRAPHICS / "app-icon-1024.png", 1024, 1024, "Press icon")

    check_screenshots("phone", "Phone screenshots")
    check_screenshots("tablet-7", "7 inch tablet")
    check_screenshots("tablet-10", "10 inch tablet")

    for name in [
        "listing.md",
        "release-notes.txt",
        "data-safety.md",
        "content-rating.md",
        "privacy-policy.md",
        "CONSOLE_CHECKLIST.md",
    ]:
        path = ROOT / "deploy/playstore" / name
        record("Documents", name, "present" if path.exists() else "missing", path.exists())

    for name in ["LumaShield-1.0.0-release.aab", "LumaShield-1.0.0-release.apk"]:
        path = ROOT / "deploy/playstore/binaries" / name
        if not path.exists():
            record("Binaries", name, "missing", False)
            continue
        megabytes = path.stat().st_size / 1024 / 1024
        record("Binaries", name, f"{megabytes:.1f} MB", megabytes < 150)

    failures = [r for r in results if not r[3]]

    lines = [
        "# Play Store asset check",
        "",
        "Generated by `tool/playstore/validate_assets.py`.",
        "",
        f"**{len(results) - len(failures)} of {len(results)} checks pass.**",
        "",
        "| Group | Asset | Detail | Result |",
        "| --- | --- | --- | --- |",
    ]
    for group, name, detail, ok in results:
        lines.append(f"| {group} | {name} | {detail} | {'PASS' if ok else 'FAIL'} |")
    lines.append("")
    if failures:
        lines.append("## Problems")
        lines.append("")
        for group, name, detail, _ in failures:
            lines.append(f"- {group} / {name}: {detail}")
    else:
        lines.append("Everything Play checks at upload time is in place.")

    REPORT.write_text("\n".join(lines) + "\n")
    write_manifest()
    print(f"{len(results) - len(failures)}/{len(results)} checks pass")
    print(f"report: {REPORT.relative_to(ROOT)}")
    return 1 if failures else 0


def write_manifest() -> None:
    """A checksum log of every deliverable, handy for upload verification."""
    import hashlib

    base = ROOT / "deploy/playstore"
    rows = ["# Deployment manifest", "", "Generated by `tool/playstore/validate_assets.py`.", "",
            "| File | Size | SHA-256 |", "| --- | --- | --- |"]
    total = 0
    for path in sorted(base.rglob("*")):
        if not path.is_file() or path.name == "MANIFEST.md":
            continue
        data = path.read_bytes()
        total += len(data)
        digest = hashlib.sha256(data).hexdigest()
        size = f"{len(data) / 1024:.0f} KB" if len(data) < 1024 * 1024 else f"{len(data) / 1048576:.1f} MB"
        rows.append(f"| `{path.relative_to(base)}` | {size} | `{digest}` |")
    rows += ["", f"**{len(rows) - 7} files, {total / 1048576:.1f} MB total.**", ""]
    (base / "MANIFEST.md").write_text("\n".join(rows))
    print("manifest: deploy/playstore/MANIFEST.md")


if __name__ == "__main__":
    sys.exit(main())
